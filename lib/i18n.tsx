const DICTS: Record<Lang, typeof ru> = { ru, kk }

export type TKey = keyof typeof ru

export function getLang(): Lang {
  if (typeof window === 'undefined') return 'ru'
  return localStorage.getItem('lang') === 'kk' ? 'kk' : 'ru'
}

export function useLang() {
  const [lang, setLangState] = useState<Lang>('ru')
  useEffect(() => { setLangState(getLang()) }, [])
  const setLang = useCallback((l: Lang) => {
    localStorage.setItem('lang', l)
    setLangState(l)
  }, [])
  const t = useCallback((k: TKey) => DICTS[lang][k] ?? ru[k] ?? k, [lang])
  return { lang, setLang, t }
}

export function LangToggle({ lang, setLang }: { lang: Lang; setLang: (l: Lang) => void }) {
  return (
    <div className="lang-toggle" role="group" aria-label="Язык / Тіл">
      <button className={lang === 'ru' ? 'active' : ''} onClick={() => setLang('ru')}>РУС</button>
      <button className={lang === 'kk' ? 'active' : ''} onClick={() => setLang('kk')}>ҚАЗ</button>
    </div>
  )
}
